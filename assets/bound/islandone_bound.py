def read_glb_json(path):
    with open(path, "rb") as f:
        data = f.read()
    jlen = struct.unpack_from("<I", data, 12)[0]
    return json.loads(data[20:20 + jlen]), data


def patch_glb(path):
    """Part material names as in the parts' GLBs and the authorship notice."""
    js, data = read_glb_json(path)
    magic, ver, _ = struct.unpack_from("<III", data, 0)
    jlen, jtype = struct.unpack_from("<II", data, 12)
    for m in js.get("materials", []):
        if m["name"].startswith("IO_MAT_Rock_Gray"):
            m["name"] = "IO_MAT_Rock_Gray"
    js.setdefault("asset", {})["copyright"] = COPYRIGHT
    js["asset"]["extras"] = dict(CREDITS)
    new = json.dumps(js, separators=(",", ":")).encode()
    new += b" " * ((4 - len(new) % 4) % 4)
    rest = data[20 + jlen:]
    with open(path, "wb") as f:
        f.write(struct.pack("<III", magic, ver, 20 + len(new) + len(rest)))
        f.write(struct.pack("<II", len(new), jtype))
        f.write(new)
        f.write(rest)


def verify_glb(path, meta):
    """Re-import into an empty scene and check what the spec asks for."""
    problems = []
    js, _ = read_glb_json(path)
    aid = meta["asset_id"]
    bpy.ops.wm.read_homefile(use_empty=True)
    bpy.ops.import_scene.gltf(filepath=path)
    ob = {o.name: o for o in bpy.data.objects}
    root = ob.get(aid)
    if root is None:
        return ["root missing"], {}
    if root.get("asset_id") != aid:
        problems.append("root extras missing")
    for o in [root] + list(root.children):
        if o.name.startswith("SOCKET_"):
            continue
        if o.matrix_world.translation.length > 1e-5 or Vector(o.matrix_world.to_euler()).length > 1e-4 \
                or (o.matrix_world.to_scale() - Vector((1, 1, 1))).length > 1e-4:
            problems.append(f"{o.name}: transform not applied")
    tris = {}
    for L in range(3):
        o = ob.get(f"{aid}_LOD{L}")
        if o is None:
            problems.append(f"LOD{L} missing")
            continue
        me = o.data
        t = tri_count(me)
        tris[f"LOD{L}"] = t
        lo, hi = TRI_BUDGET[L]
        if not lo <= t <= hi:
            problems.append(f"LOD{L}: {t} tris outside {lo}-{hi}")
        if not me.uv_layers:
            problems.append(f"LOD{L}: no UVs")
        names = sorted(m.name.split(".")[0] for m in me.materials)
        want = sorted(meta["material_ids"])
        if names != want:
            problems.append(f"LOD{L}: materials {names} != {want}")
        if not me.shape_keys or "Loose" not in me.shape_keys.key_blocks:
            problems.append(f"LOD{L}: morph Loose missing")
        zs = [v.co.z for v in me.vertices]
        if min(zs) < ROPE_FLOOR - 0.0005 or min(zs) > 0.002:
            problems.append(f"LOD{L}: lowest point {min(zs):.4f} (parts on Z = 0, rope pressed in down to {ROPE_FLOOR})")
        # outward normals: signed volume of the closed parts must be positive
        bm = bmesh.new()
        bm.from_mesh(me)
        vol = bm.calc_volume(signed=True)
        bm.free()
        if vol <= 0:
            problems.append(f"LOD{L}: normals point inwards (volume {vol:.6f})")
    col = ob.get(f"{aid}_COL")
    if col is None:
        problems.append("collider missing")
    elif col.data.materials:
        problems.append("collider has a material")
    for s in ("GRIP", "HEAD", "JOINT"):
        o = ob.get(f"SOCKET_{s}")
        if o is None:
            problems.append(f"SOCKET_{s} missing")
            continue
        want = Vector(meta["sockets"][s]["pos_blender"])
        if (o.matrix_world.translation - want).length > 1e-3:
            problems.append(f"SOCKET_{s} at {r4(o.matrix_world.translation)} != {r4(want)}")
    g = ob.get("SOCKET_GRIP")
    if g and Vector((g.matrix_world.translation.x, g.matrix_world.translation.y)).length > 1e-3:
        problems.append("pivot is not under GRIP")
    h = ob.get("SOCKET_HEAD")
    if h and h.matrix_world.translation.x <= 0:
        problems.append("head is not towards +X")
    o0 = ob.get(f"{aid}_LOD0")
    if o0:
        pts = np.array([o0.matrix_world @ v.co for v in o0.data.vertices])
        if np.ptp(pts[:, 0]) < np.ptp(pts[:, 2]):
            problems.append("orientation: not lying (X extent < Z extent)")
    imgs = len(js.get("images", []))
    mats = len(js.get("materials", []))
    info = {"tris": tris, "images": imgs, "gltf_materials": mats,
            "nodes": [n["name"] for n in js["nodes"]],
            "morph_targets": sorted({t for m in js["meshes"] for t in m.get("extras", {}).get("targetNames", [])}),
            "problems": problems, "ok": not problems}
    return problems, info


