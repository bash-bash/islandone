def add_white_color(me):
    if me.color_attributes.get("Color") is None:
        ca = me.color_attributes.new("Color", 'BYTE_COLOR', 'POINT')
        ca.data.foreach_set("color", np.ones(len(me.vertices) * 4, np.float32))


def join_meshes(meshes, mats, name):
    """Join meshes (each with one material) into one mesh with one slot per material. UVs, COLOR_0
    (white where a part has none) and the parts' own corner normals are kept as they are."""
    bm = bmesh.new()
    slot_of = {}
    out = bpy.data.meshes.new(name)
    for me, mat in zip(meshes, mats):
        if mat.name not in slot_of:
            slot_of[mat.name] = len(out.materials)
            out.materials.append(mat)
    uvl = bm.loops.layers.uv.new("UVMap")
    vcols, cnrm = [], []
    for me, mat in zip(meshes, mats):
        add_white_color(me)
        cn = np.empty(len(me.loops) * 3, np.float32)
        me.corner_normals.foreach_get("vector", cn)
        cn = cn.reshape(-1, 3)
        ca = me.color_attributes["Color"]
        cvals = np.empty(len(me.vertices) * 4, np.float32)
        ca.data.foreach_get("color", cvals)
        cvals = cvals.reshape(-1, 4)
        tmp = bmesh.new()
        tmp.from_mesh(me)
        src_uv = tmp.loops.layers.uv.get("UVMap") or tmp.loops.layers.uv.active
        vmap = {}
        for v in tmp.verts:
            vmap[v.index] = bm.verts.new(v.co)
            vcols.append(cvals[v.index])
        for f, poly in zip(tmp.faces, me.polygons):
            nf = bm.faces.new([vmap[v.index] for v in f.verts])
            nf.material_index = slot_of[mat.name]
            nf.smooth = f.smooth
            for k, (l_new, l_old) in enumerate(zip(nf.loops, f.loops)):
                l_new[uvl].uv = l_old[src_uv].uv
                cnrm.append(cn[poly.loop_start + k])
        tmp.free()
    bm.to_mesh(out)
    bm.free()
    ca = out.color_attributes.new("Color", 'BYTE_COLOR', 'POINT')
    ca.data.foreach_set("color", np.array(vcols, np.float32).ravel())
    out.color_attributes.active_color = ca
    out.normals_split_custom_set([tuple(n) for n in cnrm])
    for me in meshes:
        bpy.data.meshes.remove(me)
    return out


def rest_transform(points, down_hint=(0, 0, -1)):
    """Lay the assembly on the stable convex-hull face closest to the planned underside (like
    IO_Branch_A): coplanar hull triangles are merged, the centre of mass has to project into the
    face. Returns the rotation that turns that face down (normal -> -Z) and its tilt in degrees."""
    bm = bmesh.new()
    for p in points:
        bm.verts.new(p)
    bmesh.ops.convex_hull(bm, input=bm.verts)
    loose = [v for v in bm.verts if not v.link_faces]
    bmesh.ops.delete(bm, geom=loose, context='VERTS')
    bmesh.ops.dissolve_limit(bm, angle_limit=math.radians(1.0), verts=bm.verts, edges=bm.edges)
    bm.faces.ensure_lookup_table()
    hint = Vector(down_hint).normalized()
    com = Vector(np.mean(points, 0))
    best, best_d = None, -2
    for f in bm.faces:
        n = f.normal.copy()
        if n.dot(com - f.calc_center_median()) > 0:
            n = -n
        d = n.dot(hint)
        if d <= best_d:
            continue
        # stability: the centre of mass projected along n must fall inside the face
        q = com - n * (com - f.verts[0].co).dot(n)
        vs = [v.co for v in f.verts]
        inside = all((vs[(i + 1) % len(vs)] - vs[i]).cross(q - vs[i]).dot(n) <= 1e-9 for i in range(len(vs))) or \
            all((vs[(i + 1) % len(vs)] - vs[i]).cross(q - vs[i]).dot(n) >= -1e-9 for i in range(len(vs)))
        if inside:
            best_d, best = d, n
    bm.free()
    q = best.rotation_difference(Vector((0, 0, -1)))
    return q.to_matrix().to_4x4(), math.degrees(best.angle(hint))


class Assembly:
    """Parts placed in the variant's frame, before the rest pose: lists of (mesh, material) per LOD,
    plus key points (grip, head, joint) and the wrap frame for the Loose morph."""

    def __init__(self, parts, variant):
        self.parts, self.variant = parts, variant
        self.items = [[], [], []]       # per LOD: (mesh, material, kind)
        self.points = {}
        self.frames = {}
        self.capsules = []
        fb = parts.fiber
        if variant == "StickStone":
            self._stick_stone(fb)
        else:
            self._stick_stick(fb)

    # --- StickStone: Branch A as haft, Stone D lashed to the side of the END_B end (hatchet) ---
    def _stick_stone(self, fb):
        P = self.parts
        stone_v = np.array([v.co for v in P.stone["meshes"][0].vertices])
        bind_z = float(P.stone["sockets"]["BIND"][0][2])      # 0.035: binding height on the stone
        band = np.abs(stone_v[:, 2] - bind_z) < 0.014
        # stone turned 180 deg about Z: its back (-Y) faces the haft at +Y, the edge points -Y
        Rs = Matrix.Rotation(math.pi, 4, 'Z')
        sv = np.array([Rs @ Vector(p) for p in stone_v])
        back_y = float(sv[band & (np.abs(sv[:, 0]) < 0.05), 1].max())
        front_y = float(sv[band, 1].min())
        x_lo, x_hi = float(sv[band, 0].min()), float(sv[band, 0].max())
        c_head, r_head = P.stick_section(HEAD_X)
        # haft: Branch A rotated about its END_A ground contact so that its axis at HEAD_X sits at
        # the stone's binding height (it rests on the stone there and on END_A on the ground)
        pivot = Vector((P.end_a[0], 0.0, 0.0))
        lift = bind_z - c_head[2]
        ang = math.atan2(lift, HEAD_X - P.end_a[0])
        Mh = Matrix.Translation(pivot) @ Matrix.Rotation(-ang, 4, 'Y') @ Matrix.Translation(-pivot)
        head_c = Mh @ Vector(c_head)
        axis = (Mh.to_3x3() @ Vector(P.axis)).normalized()
        # stone placed so its back touches the haft (1 mm pressed in, it is tied tight)
        stone_off = Vector((head_c.x - 0.5 * (x_lo + x_hi), head_c.y - r_head - back_y + 0.001, 0.0))
        Ms = Matrix.Translation(stone_off) @ Rs
        RA = r_head
        contact = head_c - Vector((0, r_head, 0))
        Mw = wrap_frame(contact, axis, (0, 1, 0), RA)
        Mi = Mw.inverted()
        haft0 = copy_mesh(P.branch["meshes"][0], Mi @ Mh, "_tmp_haft")
        stone0 = copy_mesh(P.stone["meshes"][0], Mi @ Ms, "_tmp_stone")
        members = []
        # haft: main stem only (the twig near the head must not lift the rope)
        stem = lambda q: np.hypot(q[:, 1] - RA, q[:, 2]) < 1.8 * RA
        for me, keep in ((haft0, stem), (stone0, None)):
            members.append((np.array([v.co for v in me.vertices]), np.array([e.vertices[:] for e in me.edges]), keep))
            bpy.data.meshes.remove(me)
        stone_cx = float((Mi @ (Matrix.Translation(stone_off) @ Vector((0.5 * (x_lo + x_hi), 0, bind_z))))[0])
        path = make_hull_path(members, WRAP_PHI, stone_cx)
        for L in range(3):
            self.items[L].append((copy_mesh(P.branch["meshes"][L], Mh, f"_haft{L}"), P.mat_bark, "bark"))
            self.items[L].append((copy_mesh(P.stone["meshes"][L], Ms, f"_stone{L}"), P.mat_rock[L], "stone"))
            w = build_wrap_mesh(fb, L, RA, 0, 0, 0.0, 90.0, f"_wrap{L}", path_fn=path, tail_dir=(0.35, -1.0, -0.25))
            w.transform(Mw)
            self.items[L].append((w, P.mat_fiber, "wrap"))
        self.points["GRIP"] = Mh @ Vector(P.handle_grip)      # Branch A handle_grip, 0.10 m from END_A
        self.points["END_A"] = Mh @ Vector(P.end_a)
        self.points["END_B"] = Mh @ Vector(P.end_b)
        stone_c = Ms @ Vector((0.0, 0.0, bind_z))
        self.points["HEAD"] = stone_c
        self.points["JOINT"] = contact.copy()
        self.frames["axis"] = axis
        self.frames["head_normal"] = (Ms.to_3x3() @ Vector((0, 1, 0))).normalized()   # edge direction
        self.frames["joint_up"] = Vector((0, -1, 0))                                     # towards B (stone)
        self.frames["wrap"] = Mw
        self.frames["stone_matrix"] = Ms
        self.capsules.append((self.points["END_A"], self.points["END_B"], 0.024))
        self.meta = {"haft": "IO_Branch_A", "head": "IO_Stone_Small_D", "haft_tilt_deg": round(math.degrees(ang), 2),
                     "member_A_radius_m": round(RA, 4), "wrap_fit": "convex hull of haft and stone sections per turn",
                     "diagonal_tilt_deg": WRAP_PHI}

    # --- StickStick: two Branch A crossed at 62 deg near their thick ends ---
    def _stick_stick(self, fb):
        P = self.parts
        th = math.radians(CROSS_DEG["StickStick"])
        c1, r1 = P.stick_section(CROSS_X)
        c2, r2 = P.stick_section(CROSS_X)
        axis1 = Vector(P.axis)
        # stick 2: Branch A turned about Z by theta (thin ends spread apart), spun 180 deg about its own
        # axis (its twigs point up and away instead of into stick 1), resting on stick 1 at the crossing
        spin = Matrix.Translation(Vector(c2)) @ Matrix.Rotation(math.pi, 4, Vector(P.axis)) @ Matrix.Translation(-Vector(c2))
        yaw = Matrix.Rotation(th, 4, 'Z')
        # place the crossing point of stick 2 above the crossing point of stick 1
        top1 = Vector(c1) + Vector((0, 0, r1))
        p2 = yaw @ spin @ Vector(c2)
        M2 = Matrix.Translation(top1 + Vector((0, 0, r2)) - p2) @ yaw @ spin
        axis2 = (M2.to_3x3() @ Vector(P.axis)).normalized()
        contact = top1
        Mw = wrap_frame(contact, axis1, (0, 0, -1), r1)
        for L in range(3):
            self.items[L].append((copy_mesh(P.branch["meshes"][L], Matrix.Identity(4), f"_stick1_{L}"), P.mat_bark, "bark"))
            self.items[L].append((copy_mesh(P.branch["meshes"][L], M2, f"_stick2_{L}"), P.mat_bark, "bark"))
            w = build_wrap_mesh(fb, L, r1, r2, r2, WRAP_FLAT[self.variant], math.degrees(th), f"_wrap{L}")
            w.transform(Mw)
            self.items[L].append((w, P.mat_fiber, "wrap"))
        self.points["GRIP"] = Vector(P.grip_carry)
        self.points["END_A"] = Vector(P.end_a)
        self.points["END_B"] = Vector(P.end_b)
        self.points["HEAD"] = Vector(P.end_a)            # the bound end of stick 1
        self.points["JOINT"] = contact.copy()
        self.points["END_A2"] = M2 @ Vector(P.end_a)
        self.points["END_B2"] = M2 @ Vector(P.end_b)
        self.frames["axis"] = axis1
        self.frames["axis2"] = axis2
        self.frames["head_normal"] = -axis1               # HEAD points out of the bound end
        self.frames["joint_up"] = Vector((0, 0, 1))      # towards B (upper stick)
        self.frames["wrap"] = Mw
        self.frames["wrap_members"] = dict(RA=r1, wB=r2, dB=r2)
        self.capsules.append((self.points["END_A"], self.points["END_B"], 0.024))
        self.capsules.append((self.points["END_A2"], self.points["END_B2"], 0.024))
        self.meta = {"sticks": ["IO_Branch_A", "IO_Branch_A (turned 62 deg, spun 180 deg)"],
                     "crossing": "near the thick ends (END_A), 0.11 m from the broken ends",
                     "member_A_radius_m": round(r1, 4), "member_B_radius_m": round(r2, 4),
                     "B_Flat": WRAP_FLAT[self.variant], "cross_angle_deg": CROSS_DEG[self.variant]}


