def capsule_prism(p0, p1, r):
    """Square prism around a capsule with pointed ends (16 triangles), like IO_Branch_A_COL."""
    p0, p1 = Vector(p0), Vector(p1)
    d = (p1 - p0).normalized()
    up = Vector((0, 0, 1))
    side = d.cross(up).normalized()
    up = side.cross(d).normalized()
    ring = [side * r + up * r, -side * r + up * r, -side * r - up * r, side * r - up * r]
    verts = [p0 + v for v in ring] + [p1 + v for v in ring] + [p0 - d * r, p1 + d * r]
    faces = []
    for k in range(4):
        k2 = (k + 1) % 4
        faces += [(k, k2, 4 + k2), (k, 4 + k2, 4 + k)]
        faces += [(8, k2, k), (9, 4 + k, 4 + k2)]
    return verts, faces


def loose_targets(me, fiber_slot, J, axis):
    """Weak joint: the wrap turns slacken (18 % wider about the joint) and sag (6 mm)."""
    co = np.empty(len(me.vertices) * 3, np.float32)
    me.vertices.foreach_get("co", co)
    co = co.reshape(-1, 3)
    is_wrap = np.zeros(len(co), bool)
    for poly in me.polygons:
        if poly.material_index == fiber_slot:
            is_wrap[list(poly.vertices)] = True
    J = np.array(J)
    ax = np.array(axis)
    d = co - J
    along = (d @ ax)[:, None] * ax
    perp = d - along
    tgt = J + along * (1 + 0.5 * LOOSE_GROW) + perp * (1 + LOOSE_GROW)
    up = np.clip((co[:, 2] - J[2]) / 0.05 + 0.5, 0, 1)
    tgt[:, 2] -= LOOSE_DROP * (0.4 + 0.6 * up)
    tgt[:, 2] = np.maximum(tgt[:, 2], np.minimum(co[:, 2], 0.0) + ROPE_FLOOR * (co[:, 2] > 0))
    out = co.copy()
    out[is_wrap] = tgt[is_wrap]
    return out, int(is_wrap.sum())


def build_variant(parts, variant, c_root):
    A = Assembly(parts, variant)
    asset_id = f"{FAMILY}_{variant}"
    c_var = collection(asset_id, c_root)
    cols = {k: collection(f"{asset_id}_{k}", c_var) for k in ("LOD0", "LOD1", "LOD2", "Collision", "Sockets")}
    joined = []
    for L in range(3):
        meshes = [m for m, _, _ in A.items[L]]
        mats = [m for _, m, _ in A.items[L]]
        joined.append(join_meshes(meshes, mats, f"{asset_id}_LOD{L}"))
    # rest pose from LOD0 bark and stone (the rope under the parts is pressed into the sand,
    # like the stone's own 4 mm embedding): lay it on the stable hull face closest to the underside
    def solid_mask(me):
        fslot = [m.name for m in me.materials].index(parts.mat_fiber.name)
        mask = np.ones(len(me.vertices), bool)
        for poly in me.polygons:
            if poly.material_index == fslot:
                mask[list(poly.vertices)] = False
        return mask
    pts0 = np.array([v.co for v in joined[0].vertices])[solid_mask(joined[0])]
    R, tilt = rest_transform(pts0)
    pts_r = np.array([R @ Vector(p) for p in pts0])
    # yaw: stick axis along +X, head / joint towards +X
    ax_r = R.to_3x3() @ A.frames["axis"]
    g, h = R @ A.points["GRIP"], R @ A.points["HEAD"]
    if ax_r.dot(h - g) < 0:
        ax_r = -ax_r
    dirxy = Vector((ax_r.x, ax_r.y, 0)).normalized()
    Y = Matrix.Rotation(-math.atan2(dirxy.y, dirxy.x), 4, 'Z')
    M = Y @ R
    g = M @ A.points["GRIP"]
    zmin0 = float(np.min([(M @ Vector(p)).z for p in pts0]))
    T = Matrix.Translation((-g.x, -g.y, -zmin0))
    M = T @ M
    lod_meta = []
    objs = {}
    root = bpy.data.objects.new(asset_id, None)
    root.empty_display_type = 'ARROWS'
    root.empty_display_size = 0.1
    c_var.objects.link(root)
    for L, me in enumerate(joined):
        me.transform(M)
        zmin = float(np.array([v.co.z for v in me.vertices])[solid_mask(me)].min())
        if abs(zmin) > 1e-5:                              # every LOD stands on Z = 0 by itself
            me.transform(Matrix.Translation((0, 0, -zmin)))
        # rope under the parts: pressed flat into the sand, at most ROPE_FLOOR deep (stone: 4 mm embed)
        co = np.empty(len(me.vertices) * 3, np.float32)
        me.vertices.foreach_get("co", co)
        co = co.reshape(-1, 3)
        wm = ~solid_mask(me)
        co[wm, 2] = np.maximum(co[wm, 2], ROPE_FLOOR)
        me.vertices.foreach_set("co", co.ravel())
        me.update()
        o = bpy.data.objects.new(f"{asset_id}_LOD{L}", me)
        cols[f"LOD{L}"].objects.link(o)
        o.parent = root
        o["lod_level"] = L
        o["lod_max_distance_m"] = LOD_DIST[L]
        fslot = [m.name for m in me.materials].index(parts.mat_fiber.name)
        J = M @ A.points["JOINT"]
        ax = (M.to_3x3() @ A.frames["axis"]).normalized()
        tgt, nwrap = loose_targets(me, fslot, J, ax)
        o.shape_key_add(name="Basis", from_mix=False)
        k = o.shape_key_add(name="Loose", from_mix=False)
        k.data.foreach_set("co", tgt.ravel())
        k.value = 0.0
        objs[L] = o
        lod_meta.append({"node": o.name, "tris": tri_count(me), "verts": len(me.vertices),
                         "budget": TRI_BUDGET[L], "in_budget": TRI_BUDGET[L][0] <= tri_count(me) <= TRI_BUDGET[L][1],
                         "materials": [m.name for m in me.materials], "wrap_verts": nwrap,
                         "lod_max_distance_m": LOD_DIST[L]})
        if L > 0:
            o.hide_set(True)
    # collider: one capsule per stick (+ the head stone's own convex collider)
    verts, faces = [], []
    caps = []
    for p0, p1, r in A.capsules:
        q0, q1 = M @ p0, M @ p1
        v, f = capsule_prism(q0, q1, r)
        faces += [tuple(i + len(verts) for i in ff) for ff in f]
        verts += v
        caps.append({"p0": r4(q0), "p1": r4(q1), "radius": r, "p0_gltf": b2g(q0), "p1_gltf": b2g(q1)})
    if variant == "StickStone":
        sc = parts.stone_col
        Ms = M @ A.frames["stone_matrix"]
        base = len(verts)
        verts += [Ms @ Vector(v) for v in sc[0]]
        faces += [tuple(i + base for i in ff) for ff in sc[1]]
    cme = bpy.data.meshes.new(f"{asset_id}_COL")
    cme.from_pydata([tuple(v) for v in verts], [], faces)
    cme.update()
    zc = min(v.co.z for v in cme.vertices)
    col = bpy.data.objects.new(f"{asset_id}_COL", cme)
    cols["Collision"].objects.link(col)
    col.parent = root
    col.display_type = 'WIRE'
    col["collision"] = True
    col.hide_set(True)
    # sockets
    up = Vector((0, 0, 1))
    ax = (M.to_3x3() @ A.frames["axis"]).normalized()
    sockets = {}

    def socket(name, loc, x_axis, z_axis, purpose):
        e = bpy.data.objects.new(f"SOCKET_{name}.{variant}", None)
        e.empty_display_type = 'ARROWS'
        e.empty_display_size = 0.04
        cols["Sockets"].objects.link(e)
        e.parent = root
        q = frame_quat(x_axis, z_axis)
        e.rotation_mode = 'QUATERNION'
        e.location = loc
        e.rotation_quaternion = q
        e["socket"] = name
        sockets[name] = {"pos_blender": r4(loc), "pos_gltf": b2g(loc), "rot_gltf_xyzw": q2g(q),
                         "x_axis": r4(q @ Vector((1, 0, 0))), "z_axis": r4(q @ Vector((0, 0, 1))), "purpose": purpose}
    gp = M @ A.points["GRIP"]
    hp = M @ A.points["HEAD"]
    jp = M @ A.points["JOINT"]
    head_dir = (hp - gp)
    x_to_head = ax if ax.dot(head_dir) > 0 else -ax
    socket("GRIP", gp, x_to_head, up, "hand: attach to the hand bone (held state); +X along the stick towards the head")
    if variant == "StickStone":
        hn = (M.to_3x3() @ A.frames["head_normal"]).normalized()
        socket("HEAD", hp, x_to_head, hn, "centre of the stone head at binding height; +Z = direction of the cutting edge "
                                          "(striking direction), +X along the haft")
    else:
        socket("HEAD", hp, x_to_head, up, "bound end of stick 1 (broken end next to the joint); +X out of the end")
    jn = (M.to_3x3() @ A.frames["joint_up"]).normalized()
    socket("JOINT", jp, ax if ax.dot(head_dir) > 0 else -ax, jn,
           "contact point of the two parts inside the binding; +X along member A (stick), +Z towards member B")
    dims = np.ptp(np.array([v.co for v in objs[0].data.vertices]), 0)
    mn = np.min(np.array([v.co for v in objs[0].data.vertices]), 0)
    mx = np.max(np.array([v.co for v in objs[0].data.vertices]), 0)
    root["asset_id"] = asset_id
    meta = {
        "asset_id": asset_id, "family": FAMILY, "kit": KIT_ID, "category": "crafted", "sim_kind": "bound",
        "parts": A.meta, "variant": variant,
        "usage": "a bound item: two found pieces tied together by hand with fibre; the simulation stores the parts and "
                 "the joint strength",
        "pivot": "GRIP point projected onto the ground (Z = 0); stick axis along +X, head / joint towards +X",
        "rest_tilt_deg": round(tilt, 2),
        "rope_below_ground_m": round(float(min(v.co.z for v in objs[0].data.vertices)), 4),
        "lods": lod_meta, "lod_nodes": [l["node"] for l in lod_meta], "lod_max_distance_m": LOD_DIST,
        "cull_distance_m": CULL_DIST,
        "dimensions_m": r4(dims), "bbox_min_m": r4(mn), "bbox_max_m": r4(mx),
        "material_ids": ["IO_MAT_Wood_Bark", "IO_MAT_Fiber_Dry"] + (["IO_MAT_Rock_Gray"] if variant == "StickStone" else []),
        "collision_node": col.name, "collision_type": "capsule along each stick (square prism with pointed ends)"
        + (" + the stone's own convex collider" if variant == "StickStone" else ""),
        "collision_primitive": caps, "collision_tris": len(faces), "collision_zmin": round(zc, 4),
        "sockets": sockets,
        "morph_targets": {"Loose": "weak joint: wrap turns 18 % wider and sagging 6 mm; weight = 1 - joint_strength "
                                   "(or any curve the renderer likes); bark and stone do not move"},
        "states": {"lying": "default pose as exported, any yaw about Z", "held": "SOCKET_GRIP on the hand bone",
                   "joint_strength": "runtime value of island-sim; optional: Loose morph weight = 1 - strength",
                   "wet": "runtime: base colour x 0.6, roughness ~0.35 (all three materials)"},
        "copyright": COPYRIGHT,
    }
    for k, v in meta.items():
        root[k] = v if isinstance(v, (str, int, float)) else json.dumps(v)
    return root, meta, objs, col


