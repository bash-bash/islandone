def make_wrap_path(fb, RA, wB, dB):
    """wrap_loop_path of islandone_fiber.py with member A radius RA and member B half width wB /
    half depth dB instead of RA = RB = R0. With RA = wB = dB = R0 it is the original function.
    A along +X, axis at y = +RA; B along +Z, axis at y = -dB; contact at the origin."""
    ROPE = ROPE_R

    def wrap_loop_path(fam, delta, half, flat, lift):
        n = math.hypot(RA, wB)
        uvec = np.array([fam * wB, 0.0, RA]) / n
        yv = np.array([0.0, 1.0, 0.0])
        pn = np.cross(uvec, yv)
        sB = delta * (-pn[0]) / uvec[0] if abs(uvec[0]) > 1e-9 else 0.0
        sA = delta * (-pn[2]) / uvec[2]
        pts2 = []
        for k in range(half + 1):
            psi = math.pi * k / half
            c, s_ = math.cos(psi), math.sin(psi)
            if flat > 0:
                p = 8.0
                cf = math.copysign(abs(c) ** (2 / p), c)
                sf = abs(s_) ** (2 / p)
                c = (1 - flat) * c + flat * cf
                s_ = (1 - flat) * s_ + flat * sf
            pts2.append((sB + n * c, -dB - dB * s_))
        for k in range(half + 1):
            psi = math.pi - math.pi * k / half
            pts2.append((sA + n * math.cos(psi), RA + RA * math.sin(psi)))
        pts2 = np.roll(np.array(pts2), -((half + 1) + half // 2), axis=0)
        M = len(pts2)
        nr = []
        cen = pts2.mean(0)
        for i in range(M):
            tng = pts2[(i + 1) % M] - pts2[i - 1]
            nn = np.array([tng[1], -tng[0]])
            nn = nn / np.linalg.norm(nn)
            if np.dot(nn, pts2[i] - cen) < 0:
                nn = -nn
            nr.append(nn)
        nr = np.array(nr)
        out, outn = [], []
        for i in range(M):
            s, t = pts2[i]
            bump = math.exp(-((s - (sB if t < 0 else sA)) / (0.55 * n)) ** 2) if lift else 0.0
            corner = 1.0 / max(min(abs(uvec[0]), abs(uvec[2])) * math.sqrt(2), 1e-6)
            corner = min(corner, 1.6)       # very unequal members: keep the corner clearance moderate
            off = ROPE * 1.03 * (1 + (math.sqrt(2) * corner - 1) * nr[i][0] ** 2 * 0.5) + lift * bump
            s2, t2 = pts2[i] + nr[i] * off
            out.append(delta * pn + s2 * uvec + t2 * yv)
            outn.append(nr[i][0] * uvec + nr[i][1] * yv)
        return np.array(out), np.array(outn), pn

    return wrap_loop_path


def convex_hull_2d(pts):
    pts = sorted(set(map(tuple, np.round(pts, 6))))
    if len(pts) < 3:
        return np.array(pts)

    def cross(o, a, b):
        return (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0])
    lo, up = [], []
    for p in pts:
        while len(lo) >= 2 and cross(lo[-2], lo[-1], p) <= 0:
            lo.pop()
        lo.append(p)
    for p in reversed(pts):
        while len(up) >= 2 and cross(up[-2], up[-1], p) <= 0:
            up.pop()
        up.append(p)
    return np.array(lo[:-1] + up[:-1])          # counter-clockwise


def plane_section(mesh_pts, edges, p0, pn):
    """Points where the edges of a mesh cut the plane (p0, pn)."""
    d = (mesh_pts - p0) @ pn
    a, b = edges[:, 0], edges[:, 1]
    cr = (d[a] * d[b]) < 0
    f = d[a][cr] / (d[a][cr] - d[b][cr])
    return mesh_pts[a][cr] + (mesh_pts[b][cr] - mesh_pts[a][cr]) * f[:, None]


def make_hull_path(members, phi_deg, x_centre):
    """Loop path for members of very different size (thin haft + fat stone): each turn is the
    convex hull of the members' cross-sections in the turn's plane, offset by the rope radius, i.e.
    the rope pulled tight around both. The planes contain the A-B direction (Y) and a diagonal
    u = (fam*sin(phi), 0, cos(phi)), so the two families cross on the top and the underside like
    the JointWrap's diagonals. members: list of (points Nx3, edges Ex2) in the wrap frame."""
    ROPE = ROPE_R
    phi = math.radians(phi_deg)

    def wrap_loop_path(fam, delta, half, flat, lift):
        uvec = np.array([fam * math.sin(phi), 0.0, math.cos(phi)])
        yv = np.array([0.0, 1.0, 0.0])
        pn = np.cross(uvec, yv)
        p0 = np.array([x_centre, 0.0, 0.0]) + delta * pn
        sec = []
        for P, E, keep in members:
            q = plane_section(P, E, p0, pn)
            if keep is not None and len(q):
                q = q[keep(q)]
            sec.append(q)
        pts = np.vstack([q for q in sec if len(q)])
        st = np.stack([(pts - p0) @ uvec, (pts - p0) @ yv], 1)
        hull = convex_hull_2d(st)
        # densify the hull, offset it by the rope radius, resample by arc length
        dense = []
        for i in range(len(hull)):
            a, b = hull[i], hull[(i + 1) % len(hull)]
            k = max(2, int(np.linalg.norm(b - a) / 0.002))
            dense += [a + (b - a) * j / k for j in range(k)]
        dense = np.array(dense)
        nrm2 = []
        for i in range(len(dense)):
            tg = dense[(i + 1) % len(dense)] - dense[i - 1]
            nn = np.array([tg[1], -tg[0]])
            nrm2.append(nn / max(np.linalg.norm(nn), 1e-9))
        nrm2 = np.array(nrm2)
        # smooth the normals a little so the rope rounds the hull corners
        for _ in range(4):
            nrm2 = (np.roll(nrm2, 1, 0) + 2 * nrm2 + np.roll(nrm2, -1, 0))
            nrm2 /= np.linalg.norm(nrm2, axis=1)[:, None]
        off = dense + nrm2 * ROPE * 1.03
        seg = np.linalg.norm(np.diff(np.vstack([off, off[:1]]), axis=0), axis=1)
        cum = np.concatenate([[0], np.cumsum(seg)])
        M = 2 * (half + 1)
        start = int(np.argmax(off[:, 1]))                      # ring 0 behind member A (seam hidden)
        cum0 = cum[start]
        out2, outn2 = [], []
        for j in range(M):
            target = (cum0 + cum[-1] * j / M) % cum[-1]
            i = int(np.searchsorted(cum, target, side="right") - 1) % len(off)
            i2 = (i + 1) % len(off)
            f = (target - cum[i]) / max(seg[i], 1e-9)
            out2.append(off[i] + (off[i2] - off[i]) * f)
            nn = nrm2[i] + (nrm2[i2] - nrm2[i]) * f
            outn2.append(nn / np.linalg.norm(nn))
        out2, outn2 = np.array(out2), np.array(outn2)
        if np.cross(np.append(out2[1] - out2[0], 0), np.append(out2[2] - out2[1], 0))[2] < 0:
            out2, outn2 = out2[::-1], outn2[::-1]
        out, outn = [], []
        for (s_, t_), (ns, nt) in zip(out2, outn2):
            # family -1 rides over family +1 where they cross
            # (on top only: underneath, the rope is pressed between stone and ground)
            bump = lift * (max(0.0, np.dot(ns * uvec + nt * yv, (0, 0, 1))) ** 2) if lift else 0.0
            q = p0 + (s_ + ns * bump) * uvec + (t_ + nt * bump) * yv
            out.append(q)
            outn.append(ns * uvec + nt * yv)
        return np.array(out), np.array(outn), pn

    return wrap_loop_path


def add_tail(fb, mb, P, N1s, pn, sides, rng, start_i, direction):
    """The loose end of the lashing, as in the fiber kit's build_wrap (tube + frayed straw spikes),
    placed where it is seen from the gameplay camera and sized to the thinner rope."""
    R = fb.ROPE_R
    d = nrm(direction)
    start = P[start_i] - N1s[start_i] * R * 0.4
    pts = np.array([start, start + d * 0.012, start + d * 0.024])
    fb.tube_along(mb, pts, np.array([R, R * 0.95, R * 0.85]), sides, caps=(False, True), up=pn)
    tip = pts[-1]
    e1 = nrm(np.cross(d, pn))
    e2 = np.cross(d, e1)
    for k in range(6):
        a = 2 * math.pi * k / 6 + rng.uniform(-0.3, 0.3)
        off = math.cos(a) * e1 + math.sin(a) * e2
        mb.spike(tip - d * 0.003 + off * R * 0.45, nrm(d + off * 0.35), rng.uniform(0.016, 0.028),
                 0.0018, rng, bend=np.array([0, 0, -0.10]))


def build_wrap_mesh(fb, lod, RA, wB, dB, flat, theta_deg, name, path_fn=None, tail_dir=None):
    """Runs the fiber kit's build_wrap with the rope radius and member sizes of this joint.
    Returns a mesh in the wrap frame (A along +X at y=+RA, B at y=-dB, contact at the origin),
    already sheared for the crossing angle (= Cross_Angle morph of the JointWrap)."""
    th = math.radians(theta_deg)
    saved = (fb.ROPE_R, fb.wrap_loop_path, fb.line_u.__defaults__, fb.arclen_u.__defaults__)
    lay = fb.LAY * ROPE_R / fb.ROPE_R          # keep the ply twist in proportion to the thinner rope
    try:
        fb.ROPE_R = ROPE_R
        fb.wrap_loop_path = path_fn or make_wrap_path(fb, RA, wB / math.sin(th), dB)
        fb.line_u.__defaults__ = (lay, 0.0, False)
        fb.arclen_u.__defaults__ = (lay, True)
        L = dict(fb.WRAP_LODS[lod])
        own_tail = tail_dir is not None and L["tail"]
        if own_tail:
            L["tail"] = False
        mb = fb.build_wrap(L, flat=flat)
        if own_tail:
            # last turn of the family that rides on top; the end leaves it at its top front
            spacing = 2 * ROPE_R * 1.05
            delta = (L["turns"] - 1) / 2 * spacing
            P, N1s, pn = fb.wrap_loop_path(-1, delta, L["half"], flat, 2 * ROPE_R * 0.95)
            score = P[:, 2] - 0.6 * P[:, 1]
            add_tail(fb, mb, P, N1s, pn, L["sides"], np.random.default_rng(5), int(np.argmax(score)), tail_dir)
        me = mb.to_mesh(name)
    finally:
        fb.ROPE_R, fb.wrap_loop_path = saved[0], saved[1]
        fb.line_u.__defaults__, fb.arclen_u.__defaults__ = saved[2], saved[3]
    if abs(theta_deg - 90.0) > 1e-6:
        sh = Matrix.Identity(4)
        sh[0][2] = 1.0 / math.tan(th)            # x += cot(theta) * z
        me.transform(sh)
    ca = me.color_attributes.get("Col")
    if ca:
        ca.name = "Color"
    return me


def wrap_frame(contact, x_dir, toward_a, RA):
    """Wrap frame (no scale): X along A, Y towards A, Z = X x Y; origin at the contact point."""
    X = Vector(x_dir).normalized()
    Y = Vector(toward_a)
    Y = (Y - X * Y.dot(X)).normalized()
    Z = X.cross(Y)
    rot = Matrix((X, Y, Z)).transposed().to_4x4()
    return Matrix.Translation(Vector(contact)) @ rot


