    def __init__(self, assets):
        self.assets = assets
        self.files = {"branch": os.path.join(assets, "branch", "IO_Branch_A.glb"),
                      "stone": os.path.join(assets, "stone", "IO_Stone_Small_D.glb"),
                      "wrap": os.path.join(assets, "fiber", "IO_Fiber_Binding_A_JointWrap.glb"),
                      "fiber_py": os.path.join(assets, "fiber", "islandone_fiber.py")}
        for k, p in self.files.items():
            if not os.path.exists(p):
                raise FileNotFoundError(f"part missing: {p}")
        self.branch = self._import("branch", "IO_Branch_A")
        self.stone = self._import("stone", "IO_Stone_Small_D")
        wrap = self._import("wrap", "IO_Fiber_Binding_A_JointWrap")
        self.mat_bark = bpy.data.materials["IO_MAT_Wood_Bark"]
        self.mat_fiber = bpy.data.materials["IO_MAT_Fiber_Dry"]
        self.mat_rock = []
        for i in range(3):
            m = self.stone["meshes"][i].materials[0]
            m.name = f"IO_MAT_Rock_Gray_D{i}"
            self.mat_rock.append(m)
        # unused part data: leaves (not used, see README), the JointWrap meshes (regenerated)
        for me in wrap["meshes"]:
            bpy.data.meshes.remove(me)
        for me in list(bpy.data.meshes):
            if me.users == 0:
                bpy.data.meshes.remove(me)
        leaf = bpy.data.materials.get("IO_MAT_TropicalLeaf")
        if leaf:
            bpy.data.materials.remove(leaf)
        del wrap
        for img in list(bpy.data.images):
            if img.users == 0:
                bpy.data.images.remove(img)
        self.stone_col = self.stone.get("col")
        self.fiber = load_fiber_module(self.files["fiber_py"])
        self._stick_axis()

    def _import(self, key, root_name):
        before = set(bpy.data.objects)
        bpy.ops.import_scene.gltf(filepath=self.files[key])
        new = [o for o in bpy.data.objects if o not in before]
        out = {"meshes": [], "sockets": {}, "extras": {}}
        ro = bpy.data.objects.get(root_name)
        if ro is not None:
            out["extras"] = {k: ro[k] for k in ro.keys() if isinstance(ro[k], (str, int, float))}
        for i in range(3):
            o = bpy.data.objects.get(f"{root_name}_LOD{i}")
            if o is not None:
                me = o.data
                me.name = f"_part_{root_name}_LOD{i}"
                me.transform(o.matrix_world)
                me.use_fake_user = True
                out["meshes"].append(me)
        co = bpy.data.objects.get(f"{root_name}_COL")
        if co is not None:
            out["col"] = ([tuple(co.matrix_world @ v.co) for v in co.data.vertices],
                          [tuple(p.vertices) for p in co.data.polygons])
        for o in new:
            if o.name.startswith("SOCKET_"):
                out["sockets"][o.name.split(".")[0][7:]] = (o.matrix_world.translation.copy(),
                                                             o.matrix_world.to_quaternion())
        for o in new:
            bpy.data.objects.remove(o, do_unlink=True)
        return out

    def _stick_axis(self):
        s = self.branch["sockets"]
        self.end_a = np.array(s["END_A"][0])
        self.end_b = np.array(s["END_B"][0])
        self.grip_carry = np.array(s["GRIP"][0])
        try:
            self.handle_grip = np.array(json.loads(self.branch["extras"]["handle_grip"])["pos_blender_zup"])
        except (KeyError, ValueError, TypeError):
            self.handle_grip = np.array(HANDLE_GRIP)
        self.axis = nrm(self.end_b - self.end_a)
        me = self.branch["meshes"][0]
        self._bv = np.array([v.co for v in me.vertices])
        self._be = np.array([e.vertices[:] for e in me.edges])

    def stick_section(self, x):
        """Centre and radius of Branch A's main stem where the plane normal to the stick axis
        through x cuts it (twig sections excluded)."""
        t0 = (x - self.end_a[0]) / self.axis[0]
        t = (self._bv - self.end_a) @ self.axis - t0
        a, b = self._be[:, 0], self._be[:, 1]
        cross = (t[a] * t[b]) < 0
        f = t[a][cross] / (t[a][cross] - t[b][cross])
        pts = self._bv[a][cross] + (self._bv[b][cross] - self._bv[a][cross]) * f[:, None]
        c_on = self.end_a + self.axis * t0
        d = np.linalg.norm(pts - c_on, axis=1)
        pts = pts[d < 0.035]
        centre = pts.mean(0)
        rel = pts - centre
        rel -= np.outer(rel @ self.axis, self.axis)
        r = float(np.mean(np.linalg.norm(rel, axis=1)))
        return centre, r


