"""
IslandOne - bound piece generator (Blender 4.2+ / 5.x, also runs as the `bpy` package)

Builds IO_Bound_A, the `bound` items of island-sim: two found pieces the character has tied
together with fibre. It is an assembly of existing IslandOne parts, not a new design:

  IO_Bound_A_StickStone   IO_Branch_A (haft) + IO_Stone_Small_D (head) + one joint wrap
  IO_Bound_A_StickStick   two IO_Branch_A crossed near their thick ends + one joint wrap

Parts (read only, never modified):
  <assets>/branch/IO_Branch_A.glb                 bark mesh LOD0-2 and IO_MAT_Wood_Bark
  <assets>/stone/IO_Stone_Small_D.glb             stone mesh LOD0-2 and IO_MAT_Rock_Gray (per-LOD textures)
  <assets>/fiber/IO_Fiber_Binding_A_JointWrap.glb IO_MAT_Fiber_Dry (material and textures)
  <assets>/fiber/islandone_fiber.py               the joint wrap generator (build_wrap, WRAP_LODS)

The bark and stone meshes are taken from the GLBs as they are and only placed (rigid transforms).
The binding is the JointWrap of the fiber kit, generated by the fiber script's own build_wrap() for
the real member sizes (the GLB route "scale + B_Flat + Cross_Angle" shrinks the rope to 1.6-4 mm and
squashes it flat for members of 1.2-2.2 cm radius, see README). Same diagonal lashing, same turns per
LOD, same tail, same material, UV layout and COLOR_0 cavity shading.

Every variant gets LOD0-LOD2, a capsule collider along the stick, sockets GRIP / HEAD / JOINT and a
weak-joint morph target (Loose). Each GLB is re-imported into an empty scene and checked; a manifest
(bound.json) is written and, with --render, QA renders and one context render are made.

Run:
    python3 islandone_bound.py --out . --assets .. --render
    (or: blender --background --python islandone_bound.py -- --out . --assets .. --render)
Optional: --samples N (default 48), --no-blend, --quick.

Conventions (same as the other IslandOne assets):
- Blender Z-up, metres; the glTF exporter converts to Y-up for Babylon.
- Pivot = GRIP point projected onto the ground (Z = 0), stick axis along +X, head / joint towards +X.
- Sockets are empties SOCKET_<NAME>; local +X along the stick, local +Z the socket normal.
- Transforms applied; roots and LOD nodes carry no rotation or scale.
"""

