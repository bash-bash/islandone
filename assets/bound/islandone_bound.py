def nrm(v):
    v = np.asarray(v, float)
    return v / max(np.linalg.norm(v), 1e-12)


def r4(v):
    return [round(float(c), 4) for c in v]


def b2g(v):
    """Blender (x, y, z) -> glTF (x, z, -y)."""
    return [round(float(v[0]), 4), round(float(v[2]), 4), round(float(-v[1]), 4)]


def q2g(q):
    """Blender quaternion -> glTF rotation [x, y, z, w] (Y-up)."""
    m = Matrix(((1, 0, 0), (0, 0, 1), (0, -1, 0)))
    g = (m @ q.to_matrix() @ m.transposed()).to_quaternion()
    return [round(g.x, 4), round(g.y, 4), round(g.z, 4), round(g.w, 4)]


def tri_count(me):
    return sum(len(p.vertices) - 2 for p in me.polygons)


def frame_quat(x_axis, z_axis):
    x = Vector(x_axis).normalized()
    z = Vector(z_axis)
    z = (z - x * z.dot(x)).normalized()
    y = z.cross(x)
    return Matrix((x, y, z)).transposed().to_quaternion()


def collection(name, parent=None):
    c = bpy.data.collections.new(name)
    (parent or bpy.context.scene.collection).children.link(c)
    return c


def load_fiber_module(path):
    spec = importlib.util.spec_from_file_location("islandone_fiber", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


