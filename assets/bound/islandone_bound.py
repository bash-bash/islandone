def material_swatch(mats, col):
    """Materials collection: a small swatch row (not exported) so the reused part materials are
    visible in the outliner. Materials themselves cannot live in a collection."""
    verts, faces = [], []
    for i in range(len(mats)):
        x = i * 0.12
        b = len(verts)
        verts += [(x, -0.6, 0), (x + 0.1, -0.6, 0), (x + 0.1, -0.5, 0), (x, -0.5, 0)]
        faces.append((b, b + 1, b + 2, b + 3))
    me = bpy.data.meshes.new("IO_Bound_A_Materials_Swatch")
    me.from_pydata(verts, [], faces)
    for m in mats:
        me.materials.append(m)
    for i, p in enumerate(me.polygons):
        p.material_index = i
    me.uv_layers.new(name="UVMap")
    o = bpy.data.objects.new("IO_Bound_A_Materials_Swatch", me)
    col.objects.link(o)
    o.hide_render = True
    return o


def main(out_dir, assets, render=False, save_blend=True, samples=48, quick=False):
    os.makedirs(out_dir, exist_ok=True)
    bpy.ops.wm.read_homefile(use_empty=True)
    parts = Parts(assets)
    c_top = collection("IslandOne_Crafted")
    c_fam = collection("IO_Bound", c_top)
    roots, metas = {}, {}
    for i, v in enumerate(VARIANTS):
        root, meta, objs, col = build_variant(parts, v, c_fam)
        roots[v], metas[v] = root, meta
    c_mat = collection("Materials", c_top)
    mats = [parts.mat_bark] + parts.mat_rock + [parts.mat_fiber]
    material_swatch(mats, c_mat)
    # unused data from the part imports
    for me in list(bpy.data.meshes):
        if me.name.startswith("_part_"):
            bpy.data.meshes.remove(me)
    for blocks in (bpy.data.meshes, bpy.data.materials, bpy.data.images):
        for d in list(blocks):
            if d.users == 0:
                blocks.remove(d)
    glbs = {}
    for v in VARIANTS:
        path = os.path.join(out_dir, f"{FAMILY}_{v}.glb")
        export_glb(roots[v], path)
        glbs[v] = path
        metas[v]["glb_kb"] = round(os.path.getsize(path) / 1024, 1)
    # side by side in the .blend, exported at the origin
    roots["StickStick"].location = (0, 0.9, 0)
    if save_blend:
        for img in bpy.data.images:
            if img.packed_file is None and img.source == 'FILE':
                try:
                    img.pack()
                except RuntimeError:
                    pass
        bpy.ops.wm.save_as_mainfile(filepath=os.path.join(out_dir, "islandone_bound.blend"), compress=True)
    checks = {}
    for v in VARIANTS:
        problems, info = verify_glb(glbs[v], metas[v])
        checks[v] = info
        print(v, "check:", "ok" if not problems else problems)
    all_ok = all(c["ok"] for c in checks.values())
    tex = {"IO_MAT_Wood_Bark": {"from": "IO_Branch_A", "files": [f"../branch/textures/T_IO_Branch_Bark_{k}.png" for k in ("BaseColor", "Roughness", "Normal")], "size_px": 512},
           "IO_MAT_Rock_Gray": {"from": "IO_Stone_Small_D", "files": [f"../stone/textures/IO_Stone_Small_D_LOD{l}_{k}.png" for l in range(3) for k in ("BaseColor", "Roughness", "Normal")], "size_px": [256, 128, 64], "note": "one texture set per LOD, as in the stone's own GLB"},
           "IO_MAT_Fiber_Dry": {"from": "IO_Fiber_Binding_A", "files": [f"../fiber/textures/T_IO_Fiber_Dry_{k}.png" for k in ("BaseColor", "Roughness", "Normal")], "size_px": 512}}
    manifest = {
        "family": FAMILY, "kit": KIT_ID, "generator": "islandone_bound.py", "blender": bpy.app.version_string,
        "variants": {v: {k: metas[v][k] for k in metas[v]} for v in VARIANTS},
        "conventions": {"up": "Blender +Z (glTF +Y)", "units": "metres", "long_axis": "+X (GRIP -> HEAD / JOINT)",
                        "pivot": "GRIP point projected onto the ground (Z = 0)",
                        "transforms": "applied; root and LOD nodes without rotation or scale",
                        "socket_axes": "local +X along the stick towards the head, local +Z = socket normal (glTF +Y)"},
        "binding": {"source": "IO_Fiber_Binding_A JointWrap: build_wrap() of fiber/islandone_fiber.py, same turns per LOD, "
                              "tail, material, UV layout and COLOR_0",
                    "rope_radius_m": ROPE_R, "fiber_kit_rope_radius_m": 0.011,
                    "lay_length_m": round(0.09 * ROPE_R / 0.011, 4),
                    "StickStick": f"JointWrap loop path for two round members (RA = RB = stick radius), Cross_Angle {CROSS_DEG['StickStick']} deg",
                    "StickStone": f"turns are the convex hull of haft and stone sections (tight), two diagonal families tilted +-{WRAP_PHI} deg, "
                                  f"B_Flat-like box shape comes from the stone itself"},
        "materials": tex, "material_count": 3, "new_textures": 0,
        "copyright": COPYRIGHT, "credits": CREDITS, "reimport_check": checks, "reimport_check_all_ok": all_ok,
    }
    with open(os.path.join(out_dir, "bound.json"), "w") as f:
        json.dump(manifest, f, indent=2)
    print(json.dumps({v: dict(lods=[(l["node"], l["tris"], l["in_budget"]) for l in metas[v]["lods"]],
                              dims=metas[v]["dimensions_m"], kb=metas[v]["glb_kb"], ok=checks[v]["ok"])
                      for v in VARIANTS}, indent=1))
    if render:
        import bound_render
        bound_render.render_all(out_dir, assets, glbs, metas, samples, quick)
    return manifest


